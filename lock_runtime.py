"""Generate an artifact-hashed runtime lock for Linux x86_64 / CPython 3.13."""

import argparse
import json
import platform
import re
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parent


def render(report: dict) -> str:
    environment = report["environment"]
    if (
        environment["python_version"] != "3.13"
        or environment["platform_system"] != "Linux"
        or environment["platform_machine"] != "x86_64"
    ):
        raise ValueError("The deployment lock targets Linux x86_64 / Python 3.13.")
    rows = []
    for distribution in report["install"]:
        metadata = distribution["metadata"]
        name, version = metadata["name"], metadata["version"]
        digest = distribution["download_info"]["archive_info"]["hashes"]["sha256"]
        if (
            not re.fullmatch(r"[A-Za-z0-9_.-]+", name)
            or not re.fullmatch(r"[A-Za-z0-9.!+_-]+", version)
            or not re.fullmatch(r"[a-f0-9]{64}", digest)
        ):
            raise ValueError("Invalid package identity or artifact hash in pip report.")
        rows.append(f"{name.lower()}=={version} --hash=sha256:{digest}")
    if not rows:
        raise ValueError("Refusing to write an empty dependency lock.")
    return (
        "# Generated by lock_runtime.py; do not edit individual entries.\n"
        "# Target: Linux x86_64 / CPython 3.13; one selected wheel hash per package.\n"
        + "\n".join(sorted(rows))
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, help="Reuse an explicit pip dry-run report.")
    parser.add_argument("--cache-dir", type=Path)
    args = parser.parse_args()
    if (
        sys.version_info[:2] != (3, 13)
        or platform.system() != "Linux"
        or platform.machine() != "x86_64"
    ):
        raise SystemExit("Run this generator on Linux x86_64 / CPython 3.13.")
    with TemporaryDirectory(prefix="grounded-rag-lock-") as directory:
        report = args.report or Path(directory) / "report.json"
        if args.report is None:
            command = [
                sys.executable,
                "-m",
                "pip",
                "install",
                "--dry-run",
                "--ignore-installed",
                "--only-binary=:all:",
                "--report",
                str(report),
                "-r",
                str(ROOT / "requirements-runtime.in"),
            ]
            if args.cache_dir:
                command.extend(["--cache-dir", str(args.cache_dir)])
            subprocess.run(command, check=True, timeout=600)
        content = render(json.loads(report.read_text()))
        (ROOT / "requirements.lock").write_text(content)


if __name__ == "__main__":
    main()
